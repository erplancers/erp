-- Minimal H2 schema for JDBC-backed BI workspace tables used by scheduled workers.
-- Keep in sync with the production BI workspace and analytics outbox migrations.

CREATE TABLE IF NOT EXISTS bi_saved_report (
    id VARCHAR(36) PRIMARY KEY,
    owner_username VARCHAR(120) NOT NULL,
    title VARCHAR(200) NOT NULL,
    resource_slug VARCHAR(160) NOT NULL,
    query_json TEXT NOT NULL,
    shared_with_json TEXT NOT NULL DEFAULT '[]',
    shared_roles_json TEXT NOT NULL DEFAULT '[]',
    schedule_interval_minutes INTEGER,
    schedule_emails_json TEXT NOT NULL DEFAULT '[]',
    schedule_authorities_json TEXT NOT NULL DEFAULT '[]',
    next_run_at TIMESTAMP,
    last_run_at TIMESTAMP,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_bi_schedule_interval CHECK (
        schedule_interval_minutes IS NULL OR schedule_interval_minutes BETWEEN 15 AND 43200
    )
);
CREATE INDEX IF NOT EXISTS ix_bi_saved_report_owner ON bi_saved_report(owner_username, updated_at);
CREATE INDEX IF NOT EXISTS ix_bi_saved_report_schedule ON bi_saved_report(enabled, next_run_at);

CREATE TABLE IF NOT EXISTS bi_report_execution (
    id VARCHAR(36) PRIMARY KEY,
    report_id VARCHAR(36),
    requested_by VARCHAR(120) NOT NULL,
    resource_slug VARCHAR(160) NOT NULL,
    query_json TEXT NOT NULL,
    delivery_emails_json TEXT NOT NULL DEFAULT '[]',
    authorities_json TEXT NOT NULL DEFAULT '[]',
    status VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
    result_json TEXT,
    error_message VARCHAR(4000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    CONSTRAINT ck_bi_execution_status CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED'))
);
CREATE INDEX IF NOT EXISTS ix_bi_execution_queue ON bi_report_execution(status, created_at);
CREATE INDEX IF NOT EXISTS ix_bi_execution_owner ON bi_report_execution(requested_by, created_at);

CREATE TABLE IF NOT EXISTS bi_query_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(120) NOT NULL,
    resource_slug VARCHAR(160) NOT NULL,
    elapsed_ms BIGINT NOT NULL,
    cache_hit BOOLEAN NOT NULL DEFAULT FALSE,
    succeeded BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_bi_query_audit_created ON bi_query_audit(created_at);

CREATE TABLE IF NOT EXISTS analytics_event_outbox (
    event_id VARCHAR(36) PRIMARY KEY,
    aggregate_id VARCHAR(36) NOT NULL,
    topic VARCHAR(200) NOT NULL,
    event_key VARCHAR(200) NOT NULL,
    payload_json TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP,
    CONSTRAINT ck_analytics_outbox_attempts CHECK (attempts >= 0)
);
CREATE INDEX IF NOT EXISTS ix_analytics_outbox_pending
    ON analytics_event_outbox(published_at, created_at);
