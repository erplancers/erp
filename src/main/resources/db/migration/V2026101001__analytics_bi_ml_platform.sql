-- Shared metadata tables for the ERP analytics API and the separate Spark worker.
-- Tenant and scope grant tables are provisioned by administrators, never by API callers.
CREATE TABLE IF NOT EXISTS analytics_tenant_grant (
    username VARCHAR(120) NOT NULL,
    tenant_id VARCHAR(160) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (username, tenant_id)
);

CREATE TABLE IF NOT EXISTS analytics_scope_grant (
    username VARCHAR(120) NOT NULL,
    tenant_id VARCHAR(160) NOT NULL,
    scope_type VARCHAR(40) NOT NULL,
    scope_id VARCHAR(200) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (username, tenant_id, scope_type, scope_id),
    FOREIGN KEY (username, tenant_id) REFERENCES analytics_tenant_grant(username, tenant_id)
);

CREATE TABLE IF NOT EXISTS analytics_job (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(160) NOT NULL,
    requested_by VARCHAR(120) NOT NULL,
    job_type VARCHAR(80) NOT NULL,
    dataset_key VARCHAR(100) NOT NULL,
    scope_type VARCHAR(40) NOT NULL,
    parameters_json TEXT NOT NULL,
    idempotency_key VARCHAR(160),
    status VARCHAR(30) NOT NULL DEFAULT 'QUEUED',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 3,
    available_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_until TIMESTAMP,
    worker_id VARCHAR(160),
    result_json TEXT,
    error_message VARCHAR(4000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_analytics_job_status CHECK (status IN
        ('QUEUED','RUNNING','CANCEL_REQUESTED','SUCCEEDED','FAILED','CANCELLED')),
    CONSTRAINT ck_analytics_job_attempts CHECK (attempt_count >= 0 AND max_attempts BETWEEN 1 AND 10),
    CONSTRAINT uq_analytics_job_idempotency UNIQUE (tenant_id, requested_by, idempotency_key)
);
CREATE INDEX IF NOT EXISTS ix_analytics_job_claim ON analytics_job(status, available_at, created_at);
CREATE INDEX IF NOT EXISTS ix_analytics_job_owner ON analytics_job(tenant_id, requested_by, created_at);

CREATE TABLE IF NOT EXISTS analytics_experiment (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(160) NOT NULL,
    run_name VARCHAR(200) NOT NULL,
    algorithm VARCHAR(120) NOT NULL,
    parameters_json TEXT NOT NULL,
    metrics_json TEXT NOT NULL,
    input_snapshot VARCHAR(500),
    status VARCHAR(40) NOT NULL,
    created_by VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_analytics_experiment_lookup ON analytics_experiment(tenant_id, run_name, created_at);

CREATE TABLE IF NOT EXISTS analytics_model_version (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(160) NOT NULL,
    model_name VARCHAR(160) NOT NULL,
    version INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_by VARCHAR(120) NOT NULL,
    artifact_uri VARCHAR(1000) NOT NULL,
    manifest_json TEXT NOT NULL,
    metrics_json TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    promoted_at TIMESTAMP,
    promoted_by VARCHAR(120),
    retired_at TIMESTAMP,
    CONSTRAINT ck_analytics_model_version CHECK (version > 0),
    CONSTRAINT ck_analytics_model_status CHECK (status IN ('CANDIDATE','VALIDATED','PRODUCTION','RETIRED','REJECTED')),
    CONSTRAINT uq_analytics_model_version UNIQUE (tenant_id, model_name, version)
);
CREATE INDEX IF NOT EXISTS ix_analytics_model_status ON analytics_model_version(tenant_id, model_name, status);

CREATE TABLE IF NOT EXISTS analytics_drift_metric (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(160) NOT NULL,
    model_name VARCHAR(160) NOT NULL,
    model_version INTEGER NOT NULL,
    created_by VARCHAR(120) NOT NULL,
    feature_name VARCHAR(200) NOT NULL,
    population_stability_index DOUBLE PRECISION,
    sample_size BIGINT NOT NULL,
    baseline_snapshot VARCHAR(500),
    current_snapshot VARCHAR(500),
    measured_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_analytics_drift_lookup
    ON analytics_drift_metric(tenant_id, model_name, measured_at);


CREATE TABLE IF NOT EXISTS analytics_model_review (
    id VARCHAR(36) PRIMARY KEY,
    tenant_id VARCHAR(160) NOT NULL,
    model_name VARCHAR(160) NOT NULL,
    model_version INTEGER NOT NULL,
    action VARCHAR(40) NOT NULL,
    to_status VARCHAR(30) NOT NULL,
    reviewer VARCHAR(120) NOT NULL,
    review_note VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_analytics_model_review_lookup
    ON analytics_model_review(tenant_id, model_name, created_at);
